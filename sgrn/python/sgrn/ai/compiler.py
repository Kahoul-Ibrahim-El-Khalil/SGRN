"""
sgrn.ai.compiler — Action Compiler for SGRN Digital Twin.

Compiles validated ActionProposal objects into s7shell AngelScript command strings
or binary/JSON Gateway WebSocket write frames.

EXPERIMENTAL SKETCH — not part of the delivered typed-twin path. Only call
these helpers with proposals that have already passed ``SchemaChecker``
(T1 signal constraints + T2 interlocks); the AngelScript emitter refuses
anything that is not a schema-validated finite number / boolean / enum
index, and rejects identifier-shaped or string payloads that could inject
statements.
"""

import json
import math
import re
from numbers import Real
from typing import Dict, Any, Optional
from sgrn.ai.doer import ActionProposal

_IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
# Dotted field paths such as "feed_flow.rate" or "towers[0].value" are
# legitimate; anything with whitespace, semicolons, quotes or parens is not.
_FIELD = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*(\[[0-9]+\])?(\.[A-Za-z_][A-Za-z0-9_]*(\[[0-9]+\])?)*$")


class ActionCompiler:
    """Compiles verified action proposals into executable s7shell code or gateway payloads."""

    @staticmethod
    def _validated_literal(value: Any) -> str:
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, str) or value is None:
            raise ValueError(f"Refusing to emit string/None literal {value!r} as AngelScript — "
                             "only schema-validated numbers/booleans may be compiled")
        if not isinstance(value, Real) or not math.isfinite(value):
            raise ValueError(f"Refusing to emit non-finite value {value!r} as AngelScript")
        if isinstance(value, float) and value.is_integer():
            return str(int(value))
        return repr(float(value) if isinstance(value, float) else int(value))

    @staticmethod
    def compile_to_angelscript(proposal: ActionProposal, schema: Optional[Any] = None) -> str:
        """Compile an action into an executable AngelScript snippet for s7shell.

        When ``schema`` (a ``SemanticSchema``) is given, the value is
        re-validated against the field metadata before emission; without it,
        only type-level checks (finite number / bool) apply. Either way,
        strings are never interpolated — a value like
        ``"1; Supervisor.plant_estop = false"`` raises instead of becoming
        executable script.
        """
        if not _IDENT.match(proposal.target_db):
            raise ValueError(f"Invalid DB identifier {proposal.target_db!r}")
        if not _FIELD.match(proposal.field):
            raise ValueError(f"Invalid field path {proposal.field!r}")
        if schema is not None:
            meta = schema.get_field(proposal.target_db, proposal.field)
            if meta is None:
                raise ValueError(f"Unknown field '{proposal.target_db}.{proposal.field}'; refusing to compile")
            ok, err = meta.validate_value(proposal.value)
            if not ok:
                raise ValueError(f"Schema validation failed for "
                                 f"'{proposal.target_db}.{proposal.field}': {err}")
            value = proposal.value
            if isinstance(value, str) and meta.enum_map:
                value = meta.enum_map[value]
        else:
            value = proposal.value
        val_str = ActionCompiler._validated_literal(value)
        script = (
            f"// AUTO-GENERATED BY ACTION COMPILER\n"
            f"{proposal.target_db}.{proposal.field} = {val_str};\n"
            f"{proposal.target_db}.put();\n"
        )
        return script

    @staticmethod
    def compile_to_websocket_json(proposal: ActionProposal, db_number: int = 1) -> str:
        """Compiles action into a Gateway WebSocket write_area JSON command."""
        payload = {
            "type": "write_area",
            "db": db_number,
            "field": proposal.field,
            "value": proposal.value
        }
        return json.dumps(payload)
