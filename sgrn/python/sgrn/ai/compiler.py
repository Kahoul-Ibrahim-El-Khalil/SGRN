"""
sgrn.ai.compiler — Action Compiler for SGRN Digital Twin.

Compiles validated ActionProposal objects into s7shell AngelScript command strings
or binary/JSON Gateway WebSocket write frames.
"""

import json
from typing import Dict, Any
from sgrn.ai.doer import ActionProposal


class ActionCompiler:
    """Compiles verified action proposals into executable s7shell code or gateway payloads."""

    @staticmethod
    def compile_to_angelscript(proposal: ActionProposal) -> str:
        """Compiles action into an executable AngelScript snippet for s7shell execution."""
        val_str = json.dumps(proposal.value) if isinstance(proposal.value, bool) else str(proposal.value)
        script = (
            f"// AUTO-GENERATED BY ACTION COMPILER\n"
            f"{proposal.target_db}.{proposal.field} = {val_str};\n"
            f"{proposal.target_db}.put();\n"
        )
        return script

    @staticmethod
    def compile_to_websocket_json(proposal: ActionProposal, db_number: int = 1) -> str:
        """Compiles action into a Gateway WebSocket write_area JSON command."""
        payload = {
            "type": "write_area",
            "db": db_number,
            "field": proposal.field,
            "value": proposal.value
        }
        return json.dumps(payload)
