#pragma once
// sgrn/lib/datastore/include/sgrn/datastore/bootstrap/secrets-wizard.hpp
//
// The --init secrets wizard.
//
//   1. Fresh install (no .env): generates every secret with the OS CSPRNG,
//      asks two plain questions (DB name, admin email), stages a one-shot
//      admin-password bootstrap for --init-db to consume, writes .env (0600).
//   2. Existing install: fixes any leftover change_me_* placeholders and,
//      unless already done once, offers to reset the seeded admin account
//      (postgres/seeding.sql ships 'adminroot').
//
// Design rules (decided): secrets are GENERATED by default (strong, human
// choices are incidental); they are viewable afterwards via the 0600 .env;
// the ADMIN PASSWORD is the one secret that is never viewable — it is shown
// once at generation and stored only as a bcrypt hash in the database. The
// dev stack (`bun run dev`) never runs this file; dev seeding is untouched.
//
// This header stays independent of bootstrap.hpp (which includes it):
// helpers are taken from sgrn::utils / sgrn::debug instead.
// Definitions live in src/bootstrap/secrets-wizard.cpp.

#include <filesystem>
#include <string>
#include <string_view>

namespace sgrn::datastore::bootstrap::wizard
{
namespace fs = std::filesystem;

constexpr std::string_view kSeedAdminEmail = "admin@local.com";
constexpr std::string_view kEnvBootstrapDone = "SGRN_ADMIN_BOOTSTRAP";

// Wire format for the staged file initDatabaseOnly() consumes (then deletes):
inline fs::path adminBootstrapPath(const std::string& t_base_dir) {
    return fs::path(t_base_dir) / "var" / "bootstrap" / "admin.sql";
}

/// Run the wizard. No-op (with a status line) when there is nothing to fix.
void runSecretWizard(const std::string& t_base_dir, bool t_non_interactive);
} // namespace sgrn::datastore::bootstrap::wizard
