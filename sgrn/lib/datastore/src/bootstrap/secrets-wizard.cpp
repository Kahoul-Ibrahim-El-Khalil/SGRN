void runSecretWizard(const std::string& t_base_dir, bool t_non_interactive) {
    const fs::path env_path = fs::path(t_base_dir) / ".env";
    const bool fresh = !fs::exists(env_path);

    // ── Fresh install: generate everything, ask only the two plain questions ──
    if (fresh) {
        fs::create_directories(t_base_dir);
        fmt::print("\nSGRN first-install setup — secrets are generated with the OS CSPRNG.\n");
        fmt::print("Press Enter to accept every generated value; they are stored in\n");
        fmt::print(".env (owner-only) and the server manager can view them via `cat`.\n");
        fmt::print("The ADMIN PASSWORD is different: it is printed once below and is\n");
        fmt::print("not recoverable from the database afterwards.\n\n");

        std::string db_name = "sgrn";
        std::string admin_email = std::string(kSeedAdminEmail);
        if (!t_non_interactive) {
            db_name = promptLine("PostgreSQL database name [sgrn]: ");
            if (db_name.empty()) {
                db_name = "sgrn";
            }
            admin_email = promptLine(fmt::format("Admin account email [{}]: ", kSeedAdminEmail));
            if (admin_email.empty()) {
                admin_email = std::string(kSeedAdminEmail);
            }
        }

        std::string mode = "g";
        if (!t_non_interactive) {
            mode = promptLine("Secrets — [g]enerate all (recommended) or [m]anual entry: ");
        }
        const bool manual = mode == "m" || mode == "M" || mode == "manual";

        std::map<std::string, std::string> values;
        values["POSTGRES_DB"] = db_name;
        values["SGRN_ADMIN_EMAIL"] = admin_email;
        for (const auto& [key, placeholder] : secretPlaceholderMap()) {
            values[std::string(key)] =
                (manual && !t_non_interactive) ? resolveSecretValue(key, false) : generateSecretHex(secretByteLength(key));
        }

        if (std::string exe_dir = wizardExeDir(); !exe_dir.empty()) {
            values["SGRN_BIN_DIR"] = exe_dir;
        }
        if (const char* conda_prefix = ::getenv("CONDA_PREFIX"); conda_prefix != nullptr) {
            values["SGRN_DEPLOYMENT_ENV"] = conda_prefix;
        }

        writeEnvFileWithValues(env_path, sgrn::utils::env::get("USER", "admin"), t_base_dir, values);
        if (!ensureOwnerOnlyPerms(env_path)) {
            SGRN_WARN("DatastoreInit", "Could not tighten .env permissions to 0600.");
        }

        // Admin password: shown once, then only ever its bcrypt hash.
        std::string admin_password = generateSecretHex(12);
        stageAdminBootstrap(t_base_dir, admin_email, admin_password);
        fmt::print("\n  .env written (owner-only): {}\n", env_path.string());
        fmt::print("  Admin account: {} — password below (record it NOW; not viewable later)\n", admin_email);
        fmt::print("  Admin password: {}\n\n", admin_password);
        return;
    }

    // ── Existing install: fix placeholders in place; upserts preserve the rest ──
    if (auto env_result = sgrn::utils::env::loadFile(env_path); env_result.hasError()) {
        SGRN_ERROR("DatastoreInit", "Failed to load .env: {}", env_result.error());
        std::exit(EXIT_FAILURE);
    }

    // The --generate-config template writes SGRN_DEPLOYMENT_ENV=$ENV{CONDA_PREFIX}
    // unresolved (loadEnvFile does NOT expand $ENV{} — only buildTemplateResolver
    // does, for the staged config files). Every later shell invocation
    // (executeSchemaViaPsql, --rotate's psql) sources its psql path from this
    // value, so resolve it once and persist the concrete path.
    resolveEnvPlaceholderKey(env_path, "SGRN_DEPLOYMENT_ENV");

    const std::vector<std::string> placeholders = placeholderEnvKeys();
    if (!placeholders.empty()) {
        fmt::print("\n{} placeholder secret(s) still in {} — replacing now.\n", placeholders.size(), env_path.string());
        for (const std::string& key : placeholders) {
            const std::string value = resolveSecretValue(key, t_non_interactive);
            if (!upsertEnvVar(env_path, key, value)) {
                SGRN_ERROR("DatastoreInit", "Could not rewrite key {} in {}", key, env_path.string());
                std::exit(EXIT_FAILURE);
            }
            // Keep the applied value visible to this process's later calls.
            ::setenv(key.c_str(), value.c_str(), 1);
        }
        if (!ensureOwnerOnlyPerms(env_path)) {
            SGRN_WARN("DatastoreInit", "Could not tighten .env permissions to 0600.");
        }
    } else {
        fmt::print("Secrets in {} are configured (no placeholders).\n", env_path.string());
    }

    // Seeded-admin catch-up for installs whose .env predates the wizard.
    // The guard key marks "consumed & applied once by --init-db" so a re-run
    // never resets an admin password the operator has already changed.
    if (sgrn::utils::env::get(kEnvBootstrapDone.data(), "") != "1" && !fs::exists(adminBootstrapPath(t_base_dir))) {
        std::string admin_email = sgrn::utils::env::get("SGRN_ADMIN_EMAIL", std::string(kSeedAdminEmail));
        std::string admin_password;
        if (t_non_interactive) {
            // CI: never leave the shipped default in place.
            admin_password = generateSecretHex(12);
        } else {
            const std::string answer = promptLine("\nReset the seeded admin account's default password (postgres/seeding.sql)? [y/N]: ");
            if (!answer.empty() && (answer == "y" || answer == "Y" || answer == "yes")) {
                admin_password = promptSecret("  Admin password (Enter = generate): ");
                if (admin_password.empty()) {
                    admin_password = generateSecretHex(12);
                } else if (admin_password.size() < 12) {
                    fmt::print(stderr, "    too short — need at least 12 characters; keeping seeded default\n");
                    admin_password.clear();
                }
            }
        }
        if (!admin_password.empty()) {
            stageAdminBootstrap(t_base_dir, admin_email, admin_password);
            fmt::print("\n  Admin account password staged (shown once): {}\n", admin_password);
            fmt::print("  Record it now — after first login it is only ever a bcrypt hash.\n");
        }
    }
    ensureOwnerOnlyPerms(env_path);
}
