// /proc/self/exe resolution, local copy: bootstrap-helpers.hpp declares the
// same helper (currentExeDir) but this file keeps its own to avoid a
// dependency cycle through bootstrap.hpp.
std::string wizardExeDir() {
    char exe_buf[4096] = {};
    ssize_t exe_len = ::readlink("/proc/self/exe", exe_buf, sizeof(exe_buf) - 1);
    if (exe_len <= 0) {
        return {};
    }
    return fs::path(std::string(exe_buf, static_cast<size_t>(exe_len))).parent_path().string();
}

// The placeholder token bare --generate-config writes for t_key.
std::string_view placeholderFor(std::string_view t_key) {
    for (const auto& [key, token] : secretPlaceholderMap()) {
        if (key == t_key) {
            return token;
        }
    }
    return {};
}

// Full .env content for a fresh install: same layout as
// generateDefaultEnvFile() (config-gen.cpp), wizard-resolved values.
void writeEnvFileWithValues(const fs::path& t_env_path, const std::string& t_user, const std::string& t_base_dir,
    const std::map<std::string, std::string>& t_values) {
    auto value_for = [&t_values](std::string_view t_key) {
        const auto it = t_values.find(std::string(t_key));
        return it == t_values.end() ? std::string() : it->second;
    };
    auto or_default = [&value_for](std::string_view t_key, std::string_view t_default) {
        const std::string v = value_for(t_key);
        return v.empty() ? std::string(t_default) : v;
    };
    auto secret_for = [&t_values](std::string_view t_key) {
        const auto it = t_values.find(std::string(t_key));
        return it == t_values.end() ? std::string(placeholderFor(t_key)) : it->second;
    };

    std::ofstream env_out(t_env_path);
    env_out << "# ==========================================\n";
    env_out << "# SGRN Platform — Environment Configuration\n";
    env_out << "# Generated by --init; rotate with --rotate KEY=VALUE.\n";
    env_out << "# Owner-only (0600): the server manager can inspect\n";
    env_out << "# these secrets with `cat`/`sudo cat` at any time.\n";
    env_out << "# ==========================================\n\n";

    env_out << "# -- Deployment paths ----------------------------------------------------------------\n";
    env_out << "SGRN_USER=" << t_user << "\n";
    env_out << "SGRN_DATA_DIR=" << t_base_dir << "\n";
    env_out << "SGRN_BIN_DIR=" << or_default("SGRN_BIN_DIR", "/usr/local/bin") << "\n";
    env_out << "SGRN_DEPLOYMENT_ENV=" << value_for("SGRN_DEPLOYMENT_ENV") << "\n\n";

    env_out << "# -- PostgreSQL ------------------------------------------------------------------------\n";
    env_out << "POSTGRES_HOST=" << or_default("POSTGRES_HOST", "127.0.0.1") << "\n";
    env_out << "POSTGRES_PORT=" << or_default("POSTGRES_PORT", "5432") << "\n";
    env_out << "POSTGRES_DB=" << or_default("POSTGRES_DB", "sgrn") << "\n";
    env_out << "# Superuser for bootstrapping (peer auth — must match your Linux username)\n";
    env_out << "POSTGRES_SUPERUSER=" << t_user << "\n";
    env_out << "POSTGRES_PASSWORD=" << secret_for("POSTGRES_PASSWORD") << "\n\n";

    env_out << "# -- JWT (>= 32 chars for HS256) ------------------------------------------------------\n";
    env_out << "JWT_SECRET=" << secret_for("JWT_SECRET") << "\n\n";

    env_out << "# -- Garage Object Storage ------------------------------------------------------------\n";
    env_out << "# S3 API on :3900, region us-east-1 (matches sgrn.json).\n";
    env_out << "# Provision once per machine after --generate-config:\n";
    env_out << "#   garage -c $SGRN_DATA_DIR/garage/garage.toml layout assign -z dc1 -c 50G <node-id>\n";
    env_out << "#   garage -c $SGRN_DATA_DIR/garage/garage.toml layout apply --version 1\n";
    env_out
        << "#   garage -c $SGRN_DATA_DIR/garage/garage.toml key import <GARAGE_ACCESS_KEY> <GARAGE_SECRET_KEY> -n sgrn-datastore --yes\n";
    env_out << "#   garage -c $SGRN_DATA_DIR/garage/garage.toml bucket create sgrn-uploads\n";
    env_out << "#   garage -c $SGRN_DATA_DIR/garage/garage.toml bucket allow --read --write sgrn-uploads --key sgrn-datastore\n";
    env_out << "GARAGE_S3_ENDPOINT=" << or_default("GARAGE_S3_ENDPOINT", "http://127.0.0.1:3900") << "\n";
    env_out << "GARAGE_REGION=us-east-1\n";
    env_out << "GARAGE_ACCESS_KEY=" << secret_for("GARAGE_ACCESS_KEY") << "\n";
    env_out << "GARAGE_SECRET_KEY=" << secret_for("GARAGE_SECRET_KEY") << "\n";
    env_out << "GARAGE_RPC_SECRET=" << secret_for("GARAGE_RPC_SECRET") << "\n";
    env_out << "GARAGE_ADMIN_TOKEN=" << secret_for("GARAGE_ADMIN_TOKEN") << "\n";

    // Operator-facing metadata so --init-db and later tooling can find the
    // admin account; never a secret.
    env_out << "\n# -- Admin account (wizard) ------------------------------------------------------------\n";
    env_out << "SGRN_ADMIN_EMAIL=" << value_for("SGRN_ADMIN_EMAIL") << "\n";
}

// Resolve value-or-generated for one key: Enter → CSPRNG generation,
// typing → operator value (length-validated against secretMinLength).
std::string resolveSecretValue(std::string_view t_key, bool t_non_interactive) {
    while (true) {
        std::string typed;
        if (!t_non_interactive) {
            typed = promptSecret(fmt::format("  {} (Enter = generate, or type value): ", t_key));
        }
        if (typed.empty()) {
            return generateSecretHex(secretByteLength(t_key));
        }
        if (typed.size() >= secretMinLength(t_key)) {
            return typed;
        }
        fmt::print(stderr, "    too short — need at least {} characters; try again\n", secretMinLength(t_key));
        if (t_non_interactive) {
            return generateSecretHex(secretByteLength(t_key));
        }
    }
}

// Stage the one-shot SQL that resets the seeded admin's password (and email
// when the operator chose a different one). initDatabaseOnly() appends this
// to schema.sql, executes it via the same psql run, then deletes the file —
// the plaintext only ever exists until first boot.
void stageAdminBootstrap(const std::string& t_base_dir, const std::string& t_email, const std::string& t_password) {
    const fs::path admin_path = adminBootstrapPath(t_base_dir);
    fs::create_directories(admin_path.parent_path());
    std::ofstream admin_out(admin_path);
    admin_out << "-- staged by --init (secrets wizard); consumed and deleted by --init-db.\n";
    admin_out << "-- The password is mastered ONCE at generation; only its bcrypt\n";
    admin_out << "-- hash lives in core.users afterwards (trg_hash_password).\n";
    admin_out << "update core.users\n";
    admin_out << "  set password = '" << sqlEscape(t_password) << "'\n";
    admin_out << "  where email = '" << kSeedAdminEmail << "';\n";
    if (t_email != kSeedAdminEmail) {
        admin_out << "update core.users\n";
        admin_out << "  set email = '" << sqlEscape(t_email) << "'\n";
        admin_out << "  where email = '" << kSeedAdminEmail << "';\n";
    }
    ensureOwnerOnlyPerms(admin_path);
}

